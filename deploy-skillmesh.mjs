#!/usr/bin/env node
/**
 * Deploy the SkillMesh agent team directly via the running manager REST API.
 * Run from the id-agents directory: node deploy-skillmesh.mjs
 *
 * Options:
 *   --dry-run      Print what would be deployed without spawning
 *   --agent <name> Deploy a single agent by name
 */

import { processConfig } from './dist/config-parser.js';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readFileSync, existsSync } from 'node:fs';
import { spawn } from 'node:child_process';

const __dirname = dirname(fileURLToPath(import.meta.url));
const MANAGER_URL = process.env.MANAGER_URL || 'http://localhost:4100';
const CONFIG_PATH = resolve(__dirname, 'configs/skillmesh-team.yaml');
const LOCAL_AGENT_SERVER = resolve(__dirname, 'dist/local-agent-server.js');

// Directory where .env.<agent-name> files live (pre-generated by generate-agent-keys.mjs)
const AGENT_KEYS_DIR = resolve(
  __dirname,
  'workspace/projects/skillmesh/agents'
);

const args = process.argv.slice(2);
const DRY_RUN = args.includes('--dry-run');
const SINGLE = args.includes('--agent') ? args[args.indexOf('--agent') + 1] : null;

/** Parse a .env.* file into a plain object, including comment-encoded metadata. */
function parseEnvFile(path) {
  const out = {};
  try {
    for (const line of readFileSync(path, 'utf8').split('\n')) {
      const trimmed = line.trim();
      if (!trimmed) continue;
      // Extract metadata embedded as comments: "# Address: 0x...", "# Derivation: m/..."
      if (trimmed.startsWith('#')) {
        const addrMatch = trimmed.match(/^#\s*Address:\s*(0x[0-9a-fA-F]{40})/);
        if (addrMatch) { out['_ADDRESS'] = addrMatch[1]; continue; }
        const derivMatch = trimmed.match(/^#\s*Derivation:\s*(\S+)/);
        if (derivMatch) { out['_DERIVATION'] = derivMatch[1]; continue; }
        continue;
      }
      const eq = trimmed.indexOf('=');
      if (eq < 0) continue;
      const key = trimmed.slice(0, eq).trim();
      const val = trimmed.slice(eq + 1).trim().replace(/^["']|["']$/g, '');
      out[key] = val;
    }
  } catch { /* env file absent — fine */ }
  return out;
}

/** Load pre-generated SkillMesh key info for an agent (if the env file exists). */
function loadAgentKeyMeta(agentName) {
  const envPath = resolve(AGENT_KEYS_DIR, `.env.${agentName}`);
  if (!existsSync(envPath)) return null;
  const env = parseEnvFile(envPath);
  const address = env.SKILLMESH_ADDRESS || env._ADDRESS;
  const privateKey = env.SKILLMESH_PRIVATE_KEY;
  if (!privateKey || !address) return null;
  const derivation = env.SKILLMESH_KEY_PATH || env._DERIVATION;
  const indexMatch = derivation?.match(/\/(\d+)$/);
  const keyIndex = indexMatch ? Number(indexMatch[1]) : undefined;
  return {
    skillmesh_address: address,
    skillmesh_key_index: keyIndex,
    skillmesh_key_path: derivation,
    skillmesh_private_key: privateKey,
  };
}

async function managerFetch(path, opts = {}) {
  const res = await fetch(`${MANAGER_URL}${path}`, {
    headers: { 'Content-Type': 'application/json', 'x-id-team': 'skillmesh', ...opts.headers },
    ...opts,
  });
  return res;
}

console.log(`\nDeploying SkillMesh team from: ${CONFIG_PATH}`);
console.log(`Manager: ${MANAGER_URL}${DRY_RUN ? '  [DRY RUN]' : ''}\n`);

const { agents, teamName, errors } = processConfig(CONFIG_PATH, __dirname);

if (errors.length > 0) {
  console.error('❌  Config errors:');
  errors.forEach(e => console.error(`   ${e.path}: ${e.message}`));
  process.exit(1);
}

let filteredAgents = agents;
if (SINGLE) {
  filteredAgents = agents.filter(a => a.name === SINGLE);
  if (!filteredAgents.length) {
    console.error(`❌  Agent "${SINGLE}" not found in config.`);
    process.exit(1);
  }
}

console.log(`Team: ${teamName}  |  Agents: ${filteredAgents.length}${SINGLE ? ` (filter: ${SINGLE})` : ''}\n`);

if (!DRY_RUN) {
  // Ensure the skillmesh team exists
  const teamRes = await managerFetch('/teams', {
    method: 'POST',
    body: JSON.stringify({ name: 'skillmesh' }),
  });
  if (!teamRes.ok) {
    const body = await teamRes.json();
    if (!body.error?.includes('already')) {
      console.error('❌  Failed to create team:', body.error);
      process.exit(1);
    }
  }
  console.log('✓  Team "skillmesh" ready\n');

  // Fetch existing agents to skip already-deployed ones
  const existingRes = await managerFetch('/agents?team=skillmesh');
  const existingData = existingRes.ok ? await existingRes.json() : { agents: [] };
  const existingNames = new Set((existingData.agents || []).map(a => a.name));
  if (existingNames.size) {
    console.log(`Already deployed (will skip): ${[...existingNames].join(', ')}\n`);
  }
  filteredAgents = filteredAgents.filter(a => !existingNames.has(a.name));
  if (!filteredAgents.length) {
    console.log('All agents already deployed. Nothing to do.');
    process.exit(0);
  }
}

let deployed = 0;
let failed = 0;

for (const agent of filteredAgents) {
  const runtime = agent.runtime || 'claude-code-cli';
  const model = agent.model || 'claude-sonnet-4-6';
  const keyMeta = loadAgentKeyMeta(agent.name);

  if (DRY_RUN) {
    const keyNote = keyMeta ? `key ${keyMeta.skillmesh_address}` : 'new key will be derived';
    console.log(`  [dry] ${agent.name} (${runtime}/${model}) — ${keyNote}`);
    deployed++;
    continue;
  }

  const payload = {
    name: agent.name,
    model,
    runtime,
    local: true,
    plugins: agent.plugins,
    skills: agent.skills,
    verbose: agent.verbose,
    workingDirectory: agent.workingDirectory,
    agent: agent.agent,
    roleBody: agent.roleBody,
    domain: agent.domain,
    tokenId: agent.tokenId,
    address: agent.address,
    heartbeat: agent.heartbeat,
    metadata: {
      description: agent.description,
      runtime,
      // Pre-supply the existing key so the manager uses it instead of deriving a new one
      ...(keyMeta ?? {}),
    },
  };

  process.stdout.write(`  Spawning ${agent.name} (${runtime} / ${model}) ... `);

  const spawnRes = await managerFetch('/agents/spawn', {
    method: 'POST',
    body: JSON.stringify(payload),
  });

  if (!spawnRes.ok) {
    const err = await spawnRes.json();
    console.log(`❌  ${err.error || 'failed'}`);
    failed++;
    continue;
  }

  const result = await spawnRes.json();
  const keyNote = keyMeta ? keyMeta.skillmesh_address : '(new key)';
  console.log(`✓  port ${result.port}  key ${keyNote}`);

  // Start the local agent server process
  const child = spawn(process.execPath, [
    LOCAL_AGENT_SERVER,
    agent.name,
    '--team', teamName || 'skillmesh',
    '--port', String(result.port),
    '--id', result.id,
    '--dir', result.workingDirectory,
  ], {
    detached: true,
    stdio: 'ignore',
    env: {
      ...process.env,
      MANAGER_URL,
    },
  });
  child.unref();

  deployed++;
}

console.log(`\n${deployed} deployed, ${failed} failed.`);
if (deployed > 0 && !DRY_RUN) {
  console.log('\nNext: open the id-agents dashboard — all SkillMesh agents should appear under team "skillmesh".');
}
